"""
数组去重（Remove Duplicates）

算法描述：
    本实现通过双重循环比较的方式，原地移除列表中的重复元素。
    外层循环遍历每个元素，内层循环检查后续元素是否与当前元素相同，
    如果相同则将其移除。

算法步骤：
    1. 从第一个元素开始（索引 i = 0）。
    2. 用另一个指针 j 从 i + 1 开始向后扫描。
    3. 如果发现 arr[j] == arr[i]，则移除 arr[j]（原地删除）。
    4. 继续扫描直到末尾，然后 i 前进一位。
    5. 重复以上过程直到遍历完整个数组。

时间复杂度：
    - 最优：O(n)，当数组中没有重复元素时。
    - 最差：O(n^2)，当数组中所有元素都相同时，每次删除都需要移动后续元素。
    - 平均：O(n^2)，由于 pop 操作需要移动后续元素。
空间复杂度：O(1)，原地操作，不需要额外空间。

示例：
    输入：[1, 2, 2, 3, 4, 4, 5]
    输出：[1, 2, 3, 4, 5]

    输入：[1, 1, 1, 1]
    输出：[1]

    输入：[3, 1, 2, 1, 3]
    输出：[3, 1, 2]
"""


def unique(arr):
    """Remove duplicate elements from a list in-place and return it."""
    i = 0
    while i < len(arr):
        j = i + 1
        while j < len(arr):
            if arr[i] == arr[j]:
                arr.pop(j)
            j += 1
        i += 1
    return arr
