"""
选择排序（Selection Sort）

算法描述：
    选择排序是一种简单直观的排序算法。它的基本思想是：
    每次从未排序的部分中选出最小（或最大）的元素，
    将其放到已排序部分的末尾，直到所有元素都排序完毕。

算法步骤：
    1. 初始状态：整个数组为未排序区域，已排序区域为空。
    2. 在未排序区域中找到最小元素的索引。
    3. 将最小元素与未排序区域的第一个元素交换位置。
    4. 已排序区域向右扩展一个元素。
    5. 重复步骤 2-4，直到所有元素排序完毕。

时间复杂度：
    - 最优：O(n^2)，即使数组已经有序，仍需比较所有元素对。
    - 最差：O(n^2)
    - 平均：O(n^2)
    无论输入数据的初始状态如何，都需要进行 n*(n-1)/2 次比较。
空间复杂度：O(1)，原地排序，只需常数级额外空间。
稳定性：不稳定排序算法，交换操作可能改变相同元素的相对顺序。

示例：
    输入：[64, 25, 12, 22, 11]
    输出：[11, 12, 22, 25, 64]

    排序过程：
    [64, 25, 12, 22, 11]  -> 选出最小值 11，与 64 交换
    [11, 25, 12, 22, 64]  -> 选出最小值 12，与 25 交换
    [11, 12, 25, 22, 64]  -> 选出最小值 22，与 25 交换
    [11, 12, 22, 25, 64]  -> 选出最小值 25，位置不变
    [11, 12, 22, 25, 64]  -> 排序完成
"""


def select_sort(arr):
    """Sort an array in-place using selection sort and return it."""
    length = len(arr)
    for i in range(length - 1):
        min_index = i
        for j in range(i, length):
            if arr[j] < arr[min_index]:
                min_index = j
        if min_index != i:
            arr[i], arr[min_index] = arr[min_index], arr[i]
    return arr
