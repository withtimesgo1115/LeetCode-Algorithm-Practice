"""
LeetCode 8. 字符串转换整数 (atoi) (String to Integer (atoi))

请你来实现一个 myAtoi(string s) 函数，使其能将字符串转换成一个 32 位有符号整数（类似 C/C++ 中的 atoi 函数）。

函数 myAtoi(string s) 的算法如下：
    1. 读入字符串并丢弃无用的前导空格
    2. 检查下一个字符（假设还未到字符末尾）为正还是负号，读取该字符（如果有）。确定最终结果是负数还是正数。如果两者都不存在，则假定结果为正。
    3. 读入下一个字符，直到到达下一个非数字字符或到达输入的结尾。如果没有读取到数字字符，则结果为 0。
    4. 将前面读取的数字转换为整数（即 "123" -> 123，"0032" -> 32）。如果没有读入数字，则整数为 0。必要时更改符号（从步骤 2 开始）。
    5. 如果整数超过 32 位有符号整数范围 [-2^31, 2^31 - 1]，需要截断这个整数，使其保持在范围内。具体来说，小于 -2^31 的整数应该被舍入为 -2^31，大于 2^31 - 1 的整数应该被舍入为 2^31 - 1。
    6. 返回整数作为最终结果。

注意：
    - 本题中的空白字符仅包括空格字符 ' '。
    - 除了前导空格或在数字转换步骤中描述的过程之外，不要丢弃任何字符。

示例 1:
    输入: s = "42"
    输出: 42
    解释: 加粗的字符串为已经读入的字符，插入符号是当前读取指针的位置。
    第 1 步: "42"（当前没有读入字符，因为前导空格不存在）
    第 2 步: "42"（当前没有读入字符，因为这里不存在 '-' 或者 '+'）
    第 3 步: "42"（读入 "42"）
    解析得到整数 42。由于 "42" 在范围 [-2^31, 2^31 - 1] 内，最终结果为 42。

示例 2:
    输入: s = "   -42"
    输出: -42
    解释:
    第 1 步: "   -42"（读入前导空格，但忽视掉）
    第 2 步: "   -42"（读取 '-' 字符，所以结果应该是负数）
    第 3 步: "   -42"（读入 "42"）
    解析得到整数 -42。由于 "-42" 在范围 [-2^31, 2^31 - 1] 内，最终结果为 -42。

示例 3:
    输入: s = "4193 with words"
    输出: 4193
    解释:
    第 1 步: "4193 with words"（当前没有读入字符，因为前导空格不存在）
    第 2 步: "4193 with words"（当前没有读入字符，因为这里不存在 '-' 或者 '+'）
    第 3 步: "4193 with words"（读入 "4193"；由于下一个字符不是数字，停止读取）
    解析得到整数 4193。由于 "4193" 在范围 [-2^31, 2^31 - 1] 内，最终结果为 4193。

提示:
    0 <= s.length <= 200
    s 由英文字母（大写和小写）、数字（0-9）、' '、'+'、'-' 和 '.' 组成
"""

import re


def my_atoi(s: str) -> int:
    """
    Regex-based approach.

    Match optional leading whitespace followed by an optional sign and
    digits. Clamp the result to the 32-bit signed integer range
    [-2^31, 2^31 - 1].
    """
    INT_MAX = 2**31 - 1
    INT_MIN = -(2**31)

    match = re.match(r'\s*([+-]?\d*)', s)
    if match:
        num_str = match.group(1)
        if not num_str or num_str in ('+', '-'):
            return 0
        num = int(num_str)
    else:
        return 0

    if num > INT_MAX:
        return INT_MAX
    elif num < INT_MIN:
        return INT_MIN
    return num
