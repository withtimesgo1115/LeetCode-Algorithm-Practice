"""
插入排序（Insertion Sort）

算法描述：
    插入排序是一种简单直观的排序算法。它的工作原理是通过构建有序序列，
    对于未排序数据，在已排序序列中从后向前扫描，找到相应位置并插入。
    类似于打牌时整理手牌的方式。

算法步骤：
    1. 从第一个元素开始，该元素可以认为已经被排序。
    2. 取出下一个元素，在已经排序的元素序列中从后向前扫描。
    3. 如果该元素（已排序）大于新元素，将该元素移到下一位置。
    4. 重复步骤3，直到找到已排序的元素小于或者等于新元素的位置。
    5. 将新元素插入到该位置后。

时间复杂度：
    - 最优：O(n)，当输入数组已经是有序时，只需遍历一次。
    - 最差：O(n^2)，当输入数组是逆序时。
    - 平均：O(n^2)
空间复杂度：O(1)，原地排序，只需常数级额外空间。
稳定性：稳定排序算法，相等元素的相对顺序不会改变。

示例：
    输入：[5, 2, 4, 6, 1, 3]
    输出：[1, 2, 3, 4, 5, 6]

    排序过程：
    [5] 2 4 6 1 3  ->  [2, 5] 4 6 1 3  ->  [2, 4, 5] 6 1 3
    ->  [2, 4, 5, 6] 1 3  ->  [1, 2, 4, 5, 6] 3  ->  [1, 2, 3, 4, 5, 6]
"""


def insert_sort(arr):
    """Sort an array in-place using insertion sort and return it."""
    length = len(arr)
    for i in range(length):
        temp = arr[i]
        j = i
        while j > 0 and arr[j - 1] > temp:
            arr[j] = arr[j - 1]
            j -= 1
        arr[j] = temp
    return arr
